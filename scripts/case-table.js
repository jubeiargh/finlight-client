#!/usr/bin/env node
/*
 * Writes test/conformance/CASES.md: every case of conformance/conformance.md and the test
 * that runs it. Tests are named "<case id> <title>" via caseName('<id>').
 *   node scripts/case-table.js           write the table
 *   node scripts/case-table.js --check   fail if a case has no test or the table is stale
 */
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const md = fs.readFileSync(path.join(root, 'conformance', 'conformance.md'), 'utf8');
const version = fs.readFileSync(path.join(root, 'conformance', 'CONTRACT_VERSION'), 'utf8').trim();
const cases = [];
for (const line of md.split('\n')) {
  const m = /^\| ([A-Z]-\d{2}) \| (.*?) \| `?(.*?)`? \| (.*) \|$/.exec(line);
  if (m) cases.push({ id: m[1], title: m[2], fixture: m[3] });
}
const total = /Total: (\d+) cases/.exec(md);
const testDir = path.join(root, 'test', 'conformance');
const files = fs.readdirSync(testDir).filter((f) => f.endsWith('.test.ts')).sort();
const where = new Map();
for (const file of files) {
  const src = fs.readFileSync(path.join(testDir, file), 'utf8');
  for (const m of src.matchAll(/caseName\('([A-Z]-\d{2})'\)/g)) where.set(m[1], `test/conformance/${file}`);
  // Cases generated in a loop: ['P-03', ...] or ids read from fixtures (E-, W-).
  for (const m of src.matchAll(/\['([A-Z]-\d{2})',/g)) where.set(m[1], `test/conformance/${file}`);
  if (src.includes("listFixtures('fixtures/errors')")) {
    for (const c of cases) if (c.id.startsWith('E-')) where.set(c.id, `test/conformance/${file}`);
  }
  if (src.includes("listFixtures('fixtures/webhook')")) {
    for (const c of cases) if (c.id.startsWith('W-')) where.set(c.id, `test/conformance/${file}`);
  }
}
const missing = cases.filter((c) => !where.has(c.id)).map((c) => c.id);
const rows = cases.map((c) => `| ${c.id} | ${c.title.replace(/\|/g, '\\|')} | \`${where.get(c.id) ?? 'MISSING'}\` | \`${c.id} ${c.title.replace(/\|/g, '\\|')}\` |`);
const table =
  `# Conformance cases and their tests\n\n` +
  `Contract kit ${version}. Generated by \`node scripts/case-table.js\`; do not edit by hand.\n` +
  `Each case runs as its own jest test named "<id> <title>". D-10 runs one test per matrix sub-case.\n\n` +
  `| Case | Title | Test file | Test name |\n|---|---|---|---|\n${rows.join('\n')}\n\n` +
  `Cases: ${cases.length}.\n`;
const out = path.join(testDir, 'CASES.md');
const problems = [];
if (missing.length) problems.push(`cases without a test: ${missing.join(', ')}`);
if (total && Number(total[1]) !== cases.length) problems.push(`conformance.md announces ${total[1]} cases, found ${cases.length}`);
if (process.argv.includes('--check')) {
  if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== table) problems.push('test/conformance/CASES.md is stale');
  if (problems.length) {
    process.stderr.write(`case-table: ${problems.join('; ')}\n`);
    process.exit(1);
  }
  process.stdout.write(`case-table: ok, ${cases.length} cases mapped\n`);
} else {
  fs.writeFileSync(out, table);
  if (problems.length) {
    process.stderr.write(`case-table: ${problems.join('; ')}\n`);
    process.exit(1);
  }
  process.stdout.write(`case-table: wrote ${cases.length} cases\n`);
}
